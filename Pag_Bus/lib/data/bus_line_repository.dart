  /// Returns all lines for a specific company.
  static List<BusLine> getByCompany(String company) {
    return _lines.where((line) => line.company == company).toList();
  }

  /// Returns all favorite lines in their original order from [_lines].
  static List<BusLine> getFavorites() {
    return _lines.where((line) => line.isFavorite).toList();
  }

  /// Toggles the favorite status of a line by its ID.
  static void toggleFavorite(String id) {
    final line = _lines.firstWhere((l) => l.id == id);
    line.isFavorite = !line.isFavorite;
  }
